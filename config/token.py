r"""
Нормализация токена — ОДНА на весь проект.

ПОЧЕМУ ОТДЕЛЬНЫЙ МОДУЛЬ, А НЕ ФУНКЦИЯ В КЛИЕНТЕ.

Токен попадает в сеть ДВУМЯ независимыми путями:

    TinkoffClient  -> заголовок Authorization в REST
    MarketStream   -> метаданные authorization в gRPC

Второй берёт значение НЕ у клиента, а напрямую из config.settings. Пока чистка
жила внутри tinkoff_client, она чинила только один путь из двух. Это хуже, чем
не чинить вовсе: при значении в кавычках REST оживал, /api/health/figi светил
зелёным, а стрим продолжал слать Bearer "t.xxx" и молча не получал данных —
то есть диагностика говорила «исправно» при мёртвом реалтайме.

Модуль НИЧЕГО не импортирует. Именно поэтому его может звать и config.settings,
и слой сбора: обратный импорт (settings -> tinkoff_client -> httpx) был бы кругом
и тянул бы сетевую библиотеку в конфиг.
"""
from typing import Optional


def clean_token(token: Optional[str]) -> str:
    r"""
    Снять с токена мусор, который добавляет ОКРУЖЕНИЕ, а не его значение: перевод
    строки в конце (Coolify и консоль часто так и хранят), пробелы от копирования,
    обрамляющие кавычки.

    03.08 прод четыре часа стоял с live 0 из 48, владелец перевыпустил токен — не
    помогло. Ровно этот симптом даёт хвост `\n`: заголовок `Authorization: Bearer
    t.xxx\n` Tinkoff отвергает как невалидный на КАЖДОМ запросе, перевыпуск кладёт
    новое значение в то же хранилище с тем же хвостом, и 401 повторяется. Мусор
    добавляет (точнее — не снимает) наш код, поэтому снимать его обязан код, и в
    ЕДИНСТВЕННОМ месте — иначе один путь чинишь, другой нет.

    Кавычки снимаются ТОЛЬКО парные и только по краям: одиночная кавычка внутри
    значения — это часть токена, и трогать её нельзя.
    """
    t = (token or "").strip()
    if len(t) >= 2 and t[0] == t[-1] and t[0] in ("'", '"'):
        t = t[1:-1].strip()
    return t
