"""
Патч: пол по обороту больше не привязан к депозиту владельца.

Почему скриптом, а не прямой заменой файлов: src/api/main.py весит 167 КБ и
целиком его переписывать нельзя — одна обрезанная запись убьёт весь API.
Здесь меняются только найденные якоря, и если якорь не найден — файл НЕ трогается
и об этом пишется в отчёт. Скрипт всегда выходит кодом 0: о провале должен
сообщать ТЕСТ, а не красный шаг без объяснения.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VE = os.path.join(ROOT, "src", "analysis", "volume_events.py")
API = os.path.join(ROOT, "src", "api", "main.py")
ME = os.path.abspath(__file__)

VE_WHY_OLD = """# Порог взят из размера позиции Артёма (150–250 тыс ₽), а не выбран круглым.
# Минута, в которой прошло меньше его позиции, — минута, где он был бы ВСЕЙ
# ликвидностью. Такое «пришли деньги» неисполнимо, во сколько бы раз оно ни
# превышало норму. Замер по 50 бумагам наблюдения: средняя минута p10 182 тыс ₽,
# медиана 914 тыс ₽ — то есть порог режет мёртвые минуты, а не бумаги.
"""

VE_WHY_NEW = """# Порог задаётся переменной VOLUME_FLOOR_RUB и НЕ привязан к чьему-то счёту.
#
# Прежняя версия брала его из размера позиции владельца, и это была ошибка сразу
# в двух отношениях. Сканер описывает РЫНОК, а не исполнимость одной конкретной
# заявки: у читателя может быть другой депозит, и число без его ведома решало за
# него, что считается событием. И число оказалось велико: 05.08 в проде при
# 200 000 ₽ молчали 46 бумаг из 80.
#
# СМЫСЛ ПОРОГА остался тот же: отсечь минуты, где оборот настолько мал, что
# кратность к норме перестаёт что-либо значить: EUTR ×99.7 при обороте 39 тыс ₽ и
# разгоне, начинающемся с СОРОКА ЧЕТЫРЁХ рублей.
#
# Почему именно 50 000 по умолчанию — измерено, а не выбрано круглым. Замер по
# 50 бумагам наблюдения: средняя минута p10 182 тыс ₽, медиана 914 тыс ₽. Замер
# живого рынка 05.08: при 200 000 ₽ оставалось 13 событий, при 50 000 ₽ стало 26 — и
# почти все новые оказались на настоящих деньгах (UGLD 26 млн ₽, WUSH 26 млн ₽,
# MOEX 7.6 млн ₽), а освобождённым именно снижением порога — одно событие из 26
# (SELG, 483 тыс ₽). То есть старое значение глушило рынок, а не шум.
#
# Тонкую норму в знаменателе закрывает не он, а THIN_RUB ниже: это разные вопросы.
"""

VE_DEF_OLD = 'FLOOR_RUB = float(os.getenv("VOLUME_FLOOR_RUB", "200000"))'
VE_DEF_NEW = 'FLOOR_RUB = float(os.getenv("VOLUME_FLOOR_RUB", "50000"))'

#  В API меняется КОРОТКАЯ фраза, а не весь абзац: точный текст вокруг мне
#  неизвестен байт в байт, а угаданный якорь — это неприменённый патч.
API_PAIRS = [
    ("из размера позиции Артёма", "из переменной VOLUME_FLOOR_RUB"),
    ("размера позиции Артёма", "переменной VOLUME_FLOOR_RUB"),
    ("позиции Артёма", "переменной VOLUME_FLOOR_RUB"),
]

STRICT = [
    (VE, "объяснение пола по обороту", VE_WHY_OLD, VE_WHY_NEW),
    (VE, "значение пола по умолчанию", VE_DEF_OLD, VE_DEF_NEW),
]


def _read(path):
    with open(path, encoding="utf-8") as f:
        return f.read()


def _write(path, text):
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)


def main():
    print("патч пола по обороту: отвязка от депозита, версия 1")
    print("python %s, cwd %s" % (sys.version.split()[0], os.getcwd()))
    done, already, missed = [], [], []

    texts = {}
    for path, name, old, new in STRICT:
        src = texts.get(path) or _read(path)
        if new in src and old not in src:
            already.append(name)
        elif old in src:
            src = src.replace(old, new, 1)
            texts[path] = src
            done.append(name)
        else:
            missed.append(name)

    #  Ничего не пишем, пока не проверены ВСЕ строгие якоря: половина
    #  патча хуже неприменённого: она оставила бы объяснение от одного
    #  значения рядом с другим значением — ровно тот сорт расхождения,
    #  который этим патчем и лечится.
    if missed:
        print("НЕ НАЙДЕН ЯКОРЬ (файлы НЕ тронуты):")
        for n in missed:
            print(" - " + n)
        for n in done:
            print(" ? был бы применён: " + n)
        return

    for path, src in texts.items():
        _write(path, src)

    #  API — мягкая часть: если фразы нет, это не провал патча.
    api_hits = 0
    if os.path.exists(API):
        api = _read(API)
        for old, new in API_PAIRS:
            if old in api:
                api_hits += api.count(old)
                api = api.replace(old, new)
        if api_hits:
            _write(API, api)

    print("ПРИМЕНЕНО:")
    for n in done:
        print(" + " + n)
    for n in already:
        print(" = " + n + " (уже было)")
    if api_hits:
        print(" + фраза о депозите в src/api/main.py: замен сделано %d" % api_hits)
    else:
        print(" ~ в src/api/main.py фразы о депозите нет — фаил не тронут")

    try:
        os.remove(ME)
        print("Скрипт удалил себя.")
    except OSError as e:
        print("Себя не удалил (%s) — не беда." % e)


if __name__ == "__main__":
    main()
