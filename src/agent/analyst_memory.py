async def build(days: int = 30) -> dict:
    """Что я знаю о собственных сигналах и на чём ошибался."""
    from src import db
    out: dict = {"at": datetime.now(timezone.utc).isoformat(),
                 "window_days": days, "rules": ANALYST_RULES}

    # ── послужной список моих сигналов ───────────────────────────────────────
    try:
        rows = await db.list_recent_predictions(limit=300)
    except Exception as e:                                    # noqa: BLE001
        rows = []
        out["error"] = f"журнал недоступен: {type(e).__name__}"

    mine = []
    for p in rows or []:
        ctx = p.get("context") or {}
        if isinstance(ctx, str):
            try:
                import json as _j
                ctx = _j.loads(ctx)
            except Exception:
                ctx = {}
        if (ctx.get("analyst") or "").lower() in ("hyperagent", "claude-api"):
            mine.append(p)

    evaluated = [p for p in mine if p.get("realized_r") is not None]
    n = len(evaluated)
    if n:
        rs = [float(p["realized_r"]) for p in evaluated]
        wins = [r for r in rs if r > 0]
        out["track_record"] = {
            "signals_total": len(mine), "evaluated": n,
            "expectancy_r": round(sum(rs) / n, 3),
            "win_rate": round(len(wins) / n, 2),
            "best_r": max(rs), "worst_r": min(rs),
            "by_outcome": {},
        }
        for p in evaluated:
            k = p.get("outcome") or "?"
            out["track_record"]["by_outcome"][k] = \
                out["track_record"]["by_outcome"].get(k, 0) + 1
        out["track_record"]["caveat"] = (
            f"выборка {n} сигналов — этого мало для вывода о качестве. "
            "Одна выигрышная сделка не статистика.")
    else:
        out["track_record"] = {"signals_total": len(mine), "evaluated": 0,
                               "caveat": "оценённых сигналов пока нет"}

    # ── уроки, записанные системой по исходам ────────────────────────────────
    lessons = []
    for p in mine:
        if p.get("lesson"):
            lessons.append({"ticker": p.get("ticker"), "outcome": p.get("outcome"),
                            "r": p.get("realized_r"), "lesson": p["lesson"]})
    out["lessons_from_outcomes"] = lessons[:20]
    if not lessons:
        out["lessons_from_outcomes_note"] = "уроков пока нет — нужны оценённые сигналы"

    return out
