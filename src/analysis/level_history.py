"""
История конкретного уровня по секундам: что с ним происходило последние 10-60 секунд.

ЗАЧЕМ, словами Артёма: нужно не «BID сейчас 882 тыс.», а

    16:46:00 BID 500k
    16:46:03 BID 800k
    16:46:07 BID 600k
    16:46:10 исполнено 300k
    16:46:14 BID 900k

ТРЕТИЙ СЛУЧАЙ ОДНОЙ БОЛЕЗНИ. Секунды уже хранились в двух местах, и ни одно не
давало этой картины:

    LevelTracker   знает уровень, но время у него МИНУТА, а хранит он итоги:
                   «пик 1.8 млн, исполнено 1.6 млн, восстанавливался 3 раза»
    TickRing       хранит секундный ряд, но только АГРЕГАТОВ стакана: сумма
                   bid5, лучшая цена, перекос. Какой уровень менялся — нет

Последовательность конкретной цены выбрасывалась. Данные приходили — до десяти
пакетов в секунду со всеми двадцатью уровнями.

ТОЛЬКО ИЗМЕНЕНИЯ, А НЕ КАЖДАЯ СЕКУНДА. Стоящий уровень дал бы шестьдесят
одинаковых строк, и в них утонули бы те пять, которые нужны. В примере Артёма
ровно пять строк за четырнадцать секунд — записаны переходы, не состояния.

ГЛАВНОЕ РАЗЛИЧЕНИЕ: ИСПОЛНЕНО ИЛИ СНЯТО. Уровень уменьшился на 300 лотов — это
либо его съели, либо владелец убрал заявку. Смысл противоположный: в первом
случае покупатель забрал предложение, во втором продавец передумал. Различается
по объёму сделок на этой цене между пакетами стакана.

    было 800, стало 500, сделок 300   →  исполнено 300
    было 800, стало 500, сделок 0     →  снято 300
    было 800, стало 500, сделок 100   →  исполнено 100, снято 200

ОГОВОРКА ПРО ТОЧНОСТЬ ПРИВЯЗКИ. Сделки и стакан идут ДВУМЯ независимыми потоками,
поэтому сделка приписывается ближайшему следующему изменению размера. Пакеты
стакана приходят каждые 100 мс, так что обычно это одно и то же мгновение.

Но есть случай, который данные различить НЕ МОГУТ. Было 800, прошла сделка 300,
следующий пакет показывает 800, а через секунду 500. Два равноправных чтения:

    исполнено 300, долили 300, потом сняли 300      (так считает код)
    исполнено 300, а пакет просто опоздал           (тоже сходится)

Обе версии дают ту же арифметику. Код выбирает первую, потому что за секунду
проходит около десяти пакетов: если сделка не отразилась за это время, уровень
действительно долили. На пакетах, идущих реже, привязка становится догадкой —
и называть её секундной точностью нельзя.

ПОЧЕМУ В ПАМЯТИ. Та же арифметика, что и у секундного ряда: двадцать цен десять
раз в секунду на восемьдесят бумаг — миллионы строк в день против 20 ГБ
свободных. В базу уходит МИНУТНЫЙ итог уровня, и только когда на нём что-то
происходило.

ЧЕГО ЗДЕСЬ НЕТ. Ни направления, ни рекомендации. «Уровень съели и он не
вернулся» — факт. Что это значит для цены — не измерено.
"""
from typing import Optional

EVENTS = 40           # сколько последних событий держать на уровень
WINDOW = 60           # горизонт выдачи по умолчанию, секунд
MIN_SHARE = 0.05      # изменение меньше этой доли пика не событие, а дрожание
TOP_LEVELS = 5        # для скольких верхних уровней каждой стороны вести журнал

#  Насколько уровень должен быть крупным ОТНОСИТЕЛЬНО крупнейшего на своей
#  стороне, чтобы вообще получить журнал.
#
#  Зачем это, а не просто «пятёрка по размеру». Пятое место занимает кто угодно:
#  на синтетическом прогоне отбор по одному месту дал 36 тысяч вытеснений за
#  2400 пакетов — журналы не успевали накопить историю. «Крупный относительно
#  стакана» — свойство уровня, а «пятый по счёту» — свойство очереди.
#
#  Значение — ДОГАДКА. Мерить надо по живому рынку: сколько вытеснений в час.
ENTER_SHARE = 0.25

#  ЖЁСТКИЙ ПОТОЛОК журналов на бумагу и источник.
#
#  Зачем он. Журнал заводится для верхних уровней по размеру, но раз заведённый
#  ведётся и дальше — иначе крупную плиту не довести до нуля, а её финал и есть
#  самое интересное. Без потолка это правило за сессию заводит журнал на ВСЁ:
#  замер на 80 бумагах дал 6025 журналов из 6400 уровней, потому что верхняя
#  пятёрка меняется от пакета к пакету.
#
#  Вытесняется тот, у кого последнее событие давнее всех. Так плита, которую
#  едят прямо сейчас, остаётся, а случайно заглянувший в пятёрку уровень уходит.
MAX_PER_SERIES = 12

# Виды событий. Только описание произошедшего, без оценок.
APPEARED = "appeared"       # уровень появился впервые
GREW = "grew"               # объём вырос
EXECUTED = "executed"       # уменьшился, и на цене прошли сделки
PULLED = "pulled"           # уменьшился без сделок — заявку убрали
EATEN = "eaten"             # уменьшился, часть исполнена, часть снята
GONE = "gone"               # исчез из видимого стакана
RESTORED = "restored"       # вернулся после исчезновения
REFILLED = "refilled"       # сделки прошли, а размер не упал — долили


class LevelLog:
    """
    Журналы уровней. Чистый класс: ни сети, ни базы, ни времени изнутри.

    Ключ — (тикер|источник, сторона, цена), тот же, что у LevelTracker: события
    определяет он, здесь они только хранятся и читаются. Двух определений слова
    «восстановился» быть не должно — именно так расходятся модули.
    """

    def __init__(self, events: int = EVENTS, top_levels: int = TOP_LEVELS,
                 max_per_series: int = MAX_PER_SERIES):
        self.events = max(4, int(events))
        self.top_levels = max(1, int(top_levels))
        self.max_per_series = max(2, int(max_per_series))
        self.log: dict = {}            # ключ -> список событий
        self.minute: dict = {}         # (ключ, минута) -> итог минуты
        self.evicted = 0               # сколько журналов вытеснено за жизнь

    # ─── запись ──────────────────────────────────────────────────────────────

    def add(self, key: tuple, sec: int, kind: str, lots: int = 0,
            size: int = 0, traded: int = 0, pulled: int = 0) -> None:
        """
        Записать событие в СЕКУНДНЫЙ журнал.

        Кортежи, а не словари: журналов много (до нескольких тысяч уровней), и
        словарь на каждое событие обошёлся бы в десятки мегабайт.

        Минутный итог здесь НЕ трогается. Это разные вещи: в журнал попадает
        только заметное изменение, а в минуту должно попасть ВСЁ, включая мелочь
        ниже порога — иначе она исчезла бы и из базы.
        """
        if not key or not kind:
            return
        if key not in self.log:
            self._make_room(key)
        row = self.log.setdefault(key, [])
        row.append((int(sec), kind, int(lots), int(size),
                    int(traded), int(pulled)))
        if len(row) > self.events:
            del row[:-self.events]

    def _make_room(self, key: tuple) -> None:
        """
        Освободить место под новый журнал, если бумага уже на потолке.

        Вытесняется журнал с САМЫМ ДАВНИМ последним событием: плита, которую едят
        сейчас, остаётся, а случайно заглянувший в верхнюю пятёрку уровень уходит.
        """
        series = key[0] if key else None
        if series is None:
            return
        mine = [k for k in self.log if k and k[0] == series]
        if len(mine) < self.max_per_series:
            return
        # Последняя записанная секунда как мера свежести.
        oldest = min(mine, key=lambda k: self.log[k][-1][0] if self.log[k] else 0)
        del self.log[oldest]
        self.evicted += 1

    def accrue(self, key: tuple, minute: str, kind: str, lots: int = 0,
               size: int = 0, traded: int = 0, pulled: int = 0) -> None:
        """
        Копить итог уровня за минуту — то, что уйдёт в базу.

        Вызывается на КАЖДОМ изменении, а не только на заметном: сумма мелких
        исполнений за минуту может быть больше одного крупного, и терять её
        нельзя. Секунды в базу не пойдут никогда: не помещаются.
        """
        if not key or not minute:
            return
        m = self.minute.setdefault((key, minute), {
            "added": 0, "traded": 0, "pulled": 0, "restored": 0,
            "gone": 0, "peak": 0, "end_size": 0, "events": 0})
        m["events"] += 1
        m["end_size"] = size
        m["peak"] = max(m["peak"], size)
        if kind in (GREW, APPEARED, RESTORED, REFILLED):
            m["added"] += max(0, lots)
        m["traded"] += max(0, traded)
        m["pulled"] += max(0, pulled)
        if kind == RESTORED:
            m["restored"] += 1
        elif kind == GONE:
            m["gone"] += 1

    def forget(self, key: tuple) -> None:
        self.log.pop(key, None)

    def drop_completed(self, current_minute: str) -> list:
        """
        Забрать итоги всех минут, КРОМЕ текущей: она ещё набирается.

        Отдать текущую минуту значило бы записать её половину, а потом дописать
        остаток второй строкой — и суммы разошлись бы с реальностью.
        """
        out = []
        for (key, mn) in list(self.minute):
            if mn != current_minute:
                out.append((key, mn, self.minute.pop((key, mn))))
        return out

    def drop_minute(self, minute: str) -> list:
        """
        Забрать и удалить итоги указанной минуты — для записи в базу.

        Возвращает список (ключ, итог). Удаление здесь, а не у вызывающего:
        иначе накопленное за день осталось бы в памяти навсегда.
        """
        out = []
        for (key, mn) in list(self.minute):
            if mn == minute:
                out.append((key, self.minute.pop((key, mn))))
        return out

    # ─── чтение ──────────────────────────────────────────────────────────────

    def timeline(self, key: tuple, now_sec: int, lot: int = 1,
                 window: int = WINDOW) -> list:
        """
        События уровня за последние `window` секунд, от старых к новым.

        Отдаётся в РУБЛЯХ. Лотность обязательна: у UGLD лот 1000, у SBER 1, и
        «500 лотов» само по себе не значит ничего.
        """
        rows = self.log.get(key) or []
        if not rows:
            return []
        price = key[2] if len(key) > 2 else 0
        money = float(price or 0) * max(1, int(lot or 1))
        cut = int(now_sec) - max(1, int(window))
        out = []
        for sec, kind, lots, size, traded, pulled in rows:
            if sec < cut:
                continue
            e = {"sec": sec, "back": int(now_sec) - sec, "kind": kind,
                 "size_lots": size, "size_rub": round(size * money)}
            if lots:
                e["lots"] = lots
                e["rub"] = round(lots * money)
            if traded:
                e["traded_lots"] = traded
                e["traded_rub"] = round(traded * money)
            if pulled:
                e["pulled_lots"] = pulled
                e["pulled_rub"] = round(pulled * money)
            out.append(e)
        return out

    def summary(self, key: tuple, now_sec: int, lot: int = 1,
                window: int = WINDOW) -> dict:
        """
        Итог за окно: сколько добавлено, сколько исполнено, сколько снято.

        Добавленное и снятое СКЛАДЫВАЮТСЯ РАЗДЕЛЬНО. Разность скрыла бы главное:
        уровень, где долили и сняли по миллиону, и уровень, где не было ничего,
        дают одинаковый ноль.
        """
        rows = self.timeline(key, now_sec, lot=lot, window=window)
        if not rows:
            return {}
        added = sum(r.get("rub", 0) for r in rows
                    if r["kind"] in (GREW, APPEARED, RESTORED, REFILLED))
        traded = sum(r.get("traded_rub", 0) for r in rows)
        pulled = sum(r.get("pulled_rub", 0) for r in rows)
        return {
            "window_sec": window, "events": len(rows),
            "added_rub": added, "traded_rub": traded, "pulled_rub": pulled,
            "restored": sum(1 for r in rows if r["kind"] == RESTORED),
            "gone": sum(1 for r in rows if r["kind"] == GONE),
            "size_now_rub": rows[-1]["size_rub"],
            "first_back_sec": rows[0]["back"],
            "last_back_sec": rows[-1]["back"],
        }

    def stats(self) -> dict:
        return {"levels_logged": len(self.log),
                "events_held": sum(len(v) for v in self.log.values()),
                "minutes_pending": len(self.minute),
                "evicted": self.evicted,
                "max_per_series": self.max_per_series}
