"""
Лоты в рубли. Чистая арифметика, без сети и без базы.

Зачем отдельный модуль ради двух формул. Во-первых, его можно импортировать в
тестах без SQLAlchemy и без конфига — в CI стоит только pytest и httpx, и
тест, требующий базы, там просто не запустится. Во-вторых, эта арифметика
нужна в трёх местах сразу: при записи свечи, при чтении серий и в срезе для
вердикта. Три копии одной формулы разойдутся, это вопрос времени.

ПОЧЕМУ ЭТО ВООБЩЕ ВАЖНО. Всё, что приходит от биржи, измеряется в ЛОТАХ, а
лот у бумаг разный: у FEES это 10000 акций, у SBER 10, у многих 1. Значит
«1000 лотов» у двух бумаг могут отличаться на четыре порядка. Любое сравнение
бумаг между собой — «топ-10 по изменению оборота», «оборот 3.5× нормы» — в лотах
бессмысленно.

ГЛАВНОЕ РЕШЕНИЕ ЗДЕСЬ: при НЕИЗВЕСТНОЙ лотности возвращается None, а не ноль и
не лотность 1 по умолчанию. Подставить единицу заманчиво и нельзя: оборот FEES
занизился бы в десять тысяч раз, а выглядело бы это не как ошибка, а как тихая
бумага, которую нечего смотреть. Молчаливо правдоподобное число хуже
отсутствующего: отсутствующее заметно.
"""
from typing import Optional


def bar_price(open_: Optional[float] = None, high: Optional[float] = None,
              low: Optional[float] = None,
              close: Optional[float] = None) -> Optional[float]:
    """Цена, по которой считать оборот бара: (high + low + close) / 3.

    Берётся не close, потому что весь объём минуты торговался не по цене
    закрытия, а по всему диапазону. На резкой минуте разница доходит до
    процента — именно на таких минутах и смотрят оборот.

    Это ОЦЕНКА, а не точное число. Точный оборот даёт сумма цена×объём по
    сделкам (flow_minute.vwap_num) или поле value у ISS. Ошибка здесь ограничена
    шириной минуты и обычно меньше доли процента.

    Ноли игнорируются: в недозаполненной свече low может быть нулём, и
    усреднение с нулём занизило бы цену втрое.
    """
    vals = [v for v in (high, low, close) if isinstance(v, (int, float)) and v > 0]
    if vals:
        return sum(vals) / len(vals)
    if isinstance(open_, (int, float)) and open_ > 0:
        return float(open_)
    return None


def turnover_rub(volume_lots: Optional[float], lot: Optional[int],
                 price: Optional[float]) -> Optional[float]:
    """Оборот в рублях = лоты × размер лота × цена.

    None означает «посчитать нельзя» и возвращается, если неизвестна лотность
    или нет цены. Ноль означает «торговали на ноль рублей» и возвращается
    только при нулевом объёме. Это разные вещи, и смешивать их нельзя: первое
    — наш пробел, второе — факт о рынке.

    Отрицательный объём — это повреждённые данные, а не продажа; тоже None.
    """
    if not isinstance(price, (int, float)) or price <= 0:
        return None
    if not isinstance(lot, (int, float)) or int(lot) < 1:
        return None
    if not isinstance(volume_lots, (int, float)) or volume_lots < 0:
        return None
    return round(float(volume_lots) * int(lot) * float(price), 2)


def candle_turnover_rub(row: dict, lot: Optional[int]) -> Optional[float]:
    """Оборот минутной свечи в рублях. Удобная обёртка над двумя верхними."""
    row = row or {}
    price = bar_price(row.get("open"), row.get("high"),
                      row.get("low"), row.get("close"))
    return turnover_rub(row.get("volume"), lot, price)
