# ── Имя эмитента совпадает с названием ПЛОЩАДКИ или индекса ───────────────────
# Русский трейдер говорит «на Мосбирже» в смысле «на бирже», а «индекс Мосбиржи»
# это рынок целиком — ни то, ни другое не новость об эмитенте MOEX. Замер 30.07:
# из семи новостей, привязанных к MOEX, пять (71%) были указанием места или
# упоминанием индекса, и одна из них подняла ложное новостное событие news_observe.
# Настоящих новостей эмитента было две: про запуск вечных фьючерсов.
#
# Привязку оставляем, только если в тексте есть упоминание ВНЕ такого контекста.
VENUE_CONTEXT: dict[str, tuple[str, ...]] = {
    "MOEX": (
        r"(?:на|в|с|со|для)\s+(?:мосбирж\w*|московской\s+бирж\w*)",
        r"индекс\w*\s+(?:мосбирж\w*|московской\s+бирж\w*|мб\b)",
        r"(?:мосбирж\w*|московской\s+бирж\w*)\s+индекс\w*",
    ),
}


def _venue_only(ticker: str, text_lower: str) -> bool:
    """Все упоминания тикера — про площадку или индекс, а не про эмитента."""
    pats = VENUE_CONTEXT.get(ticker)
    if not pats:
        return False
    stripped = text_lower
    for pat in pats:
        stripped = re.sub(pat, lambda m: " " * len(m.group(0)), stripped)
    # осталось ли упоминание вне «площадочного» контекста
    for alias, tk in RUSSIAN_ALIASES.items():
        if tk != ticker:
            continue
        stem = alias[:-1] if (len(alias) >= MIN_ALIAS_FOR_SUFFIX
                              and alias[-1] in "ьйяоеа") else alias
        tail = r"[а-яё]{0,3}" if len(alias) >= MIN_ALIAS_FOR_SUFFIX else ""
        if re.search(r"\b" + re.escape(stem) + tail + r"\b", stripped):
            return False
    return True


def extract_tickers(text: str) -> list[str]:
    """
    Извлечь все упомянутые тикеры Мосбиржи из текста.
    
    Args:
        text: текст сообщения
        
    Returns:
        Список уникальных тикеров (например, ["SBER", "GAZP"])
        
    Examples:
        >>> extract_tickers("Сбер идёт вниз, газик держится")
        ["SBER", "GAZP"]
        
        >>> extract_tickers("$LKOH сегодня сильная, покупаю")
        ["LKOH"]
    """
    found = set()

    # 1. Русские алиасы (сленг)
    #
    # Порядок и вычёркивание обязательны. «Газпром нефть» совпадает и с
    # «газпром нефть» (SIBN), и с «газпром» (GAZP) — это разные компании, и без
    # приоритета длинного совпадения текст уходил в GAZP. Так же «сургутнефтегаз
    # преф» (SNGSP) против «сургутнефтегаз» (SNGS): обычка вместо префов.
    #
    # Терпимость к падежам: русский текст пишет «Сбера», «по Лукойлу»,
    # «Газпрома», а поиск по точной границе слова находил только именительный.
    # Допускаем до трёх букв окончания, но ТОЛЬКО для псевдонимов от пяти
    # символов: у коротких («лук», «дно») это множит ложные срабатывания.
    text_lower = text.lower()
    consumed = text_lower
    for alias, ticker in sorted(RUSSIAN_ALIASES.items(),
                                key=lambda kv: len(kv[0]), reverse=True):
        stem = alias
        tail = ""
        if len(alias) >= MIN_ALIAS_FOR_SUFFIX:
            # При склонении конечный мягкий знак или гласная ЗАМЕНЯЮТСЯ, а не
            # дополняются: норникель -> норникелем, русгидро -> русгидрой.
            # Поэтому такую букву отбрасываем и разрешаем окончание.
            if alias[-1] in "ьйяоеа":
                stem = alias[:-1]
            tail = r"[а-яё]{0,3}"
        pattern = r"\b" + re.escape(stem) + tail + r"\b"
        m = re.search(pattern, consumed)
        if m:
            found.add(ticker)
            # вычёркиваем найденное, чтобы более короткий псевдоним внутри него
            # не сработал вторым и не привёл к другой бумаге
            consumed = consumed[:m.start()] + " " * (m.end() - m.start()) + consumed[m.end():]

    # 2. Английские тикеры с $ или # префиксом
    for pattern in TICKER_PATTERNS[:2]:
        for match in re.finditer(pattern, text, re.IGNORECASE):
            ticker = match.group(1).upper()
            if ticker in ALL_TICKERS:
                found.add(ticker)

    # 3. Чистые uppercase слова (без $/#) — только если в нашем списке тикеров
    for match in re.finditer(r"\b([A-Z]{2,8})\b", text):
        ticker = match.group(1).upper()
        if ticker in ALL_TICKERS and ticker not in STOPWORDS:
            found.add(ticker)

    # Снимаем привязку, если бумага упомянута только как площадка или индекс.
    for tk in list(found):
        if tk in VENUE_CONTEXT and _venue_only(tk, text_lower):
            found.discard(tk)

    return sorted(found)


def get_ticker_name(ticker: str) -> Optional[str]:
    """Получить русское название компании по тикеру"""
    return MOEX_TICKERS.get(ticker.upper())


def is_market_related(text: str) -> bool:
    """
    Быстрая проверка: является ли текст рыночным (упоминает акции/торговлю)?
    Используем для отфильтровки нерелевантных сообщений.
    """
    market_keywords = [
        "акци", "рынок", "индекс", "портфель", "инвести", "торгов",
        "биржа", "бумаг", "дивиденд", "прибыл", "убыток", "позици",
        "шорт", "лонг", "buy", "sell", "hold", "стоп", "тейк",
        "profit", "loss", "иис", "офз", "ipo", "spo", "etf", "пай",
        "брокер", "сигнал", "тренд", "поддержк", "сопротивлен",
        "пробой", "отскок", "коррекц", "ралли", "pump", "dump",
        "%", "₽", "руб", "rub"
    ]
    text_lower = text.lower()
    
    # Если есть тикер — уже рыночное
    if extract_tickers(text):
        return True
    
    # Иначе проверяем ключевые слова
    return any(kw in text_lower for kw in market_keywords)


def is_noise(text: str) -> bool:
    """
    Обратная функция к is_market_related.
    Возвращает True если текст НЕ относится к рынку (шум, реклама, флуд).
    Используется в бэкфилле для отсева нерелевантных сообщений.
    """
    if not text or len(text.strip()) < 5:
        return True
    return not is_market_related(text)
