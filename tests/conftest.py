"""
Общие правила для всей суиты.

СВЕЖАЯ ПЕТЛЯ СОБЫТИЙ КАЖДОМУ ТЕСТУ. Без этого суита зависела от ПОРЯДКА, и
двенадцать тестов падали, будучи полностью исправными:

    tests/test_source_health.py    по одному — 7 проходят
    tests/test_setup_watcher.py    по одному — 20 проходят
    вся суита                      12 падений: «нет текущей петли»

Причина не в Python 3.9 и не в самих тестах. `asyncio.run()` в
`test_outcome_window.py` после себя ОБНУЛЯЕТ текущую петлю, и всё, что дальше
зовёт `asyncio.get_event_loop()`, получает RuntimeError. Кто упадёт — решает
алфавит имён файлов.

В `test_stream.py` этот же приём уже был применён вручную, и там стоит
комментарий: «удобство в тесте, поломка у соседа». Правило было верное, но
жило в одном файле.

ПОЧЕМУ ЭТО ВАЖНЕЕ, ЧЕМ ДВЕНАДЦАТЬ ТЕСТОВ. Постоянно красная суита приучает не
смотреть на красное: «падений прежние» я писал в каждом отчёте за день, и это
ровно тот ярлык, который позволяет чему-то остаться непроверенным. Пока красное
привычно, новое падение неотличимо от старого.
"""
import asyncio

import pytest


@pytest.fixture(autouse=True)
def _fresh_event_loop():
    """
    Своя петля на каждый тест, и прежняя возвращается на место.

    Autouse намеренно: правило должно действовать на класс ошибки, а не на те
    файлы, где о нём вспомнили. Стоимость — создание петли, микросекунды.
    """
    try:
        prev = asyncio.get_event_loop_policy().get_event_loop()
    except RuntimeError:
        prev = None
    loop = asyncio.new_event_loop()
    asyncio.set_event_loop(loop)
    try:
        yield loop
    finally:
        try:
            loop.close()
        except Exception:                                    # noqa: BLE001
            pass
        asyncio.set_event_loop(prev)


#  Файлы, чьи фикстуры описывают ОБНАРУЖЕНИЕ, а не время.
#
#  Список ПОИМЁННЫЙ и должен таким остаться. Снять порог всем разом — значит
#  оставить непроверенным то, ради чего порог заводился; поэтому у свежести
#  есть собственные наборы, и их в этом списке нет.
_TIMELESS = {
    "test_volume_events.py",
    "test_price_events.py",
    "test_timeframes.py",
    "test_card.py",
}

#  Что именно снимается: порог возраста и порог разрыва. Оба — про время.
_LIFTED = ("max_age", "max_hole")


def _lift(monkeypatch, module_name):
    try:
        mod = __import__(module_name, fromlist=["DEFAULTS"])
    except Exception:                                        # noqa: BLE001
        return
    d = getattr(mod, "DEFAULTS", None)
    if not isinstance(d, dict):
        return
    for key in _LIFTED:
        if key in d:
            monkeypatch.setitem(d, key, 10 ** 9)


@pytest.fixture(autouse=True)
def _timeless_scanner_fixtures(request, monkeypatch):
    """
    Снять пороги времени ровно тем файлам, где бары нарисованы руками.

    ЗАЧЕМ. Сканеры перестали считать событием старый бар: если поток встал в
    14:10, в 16:00 нельзя писать «оборот в 12 раз выше нормы» или «резкий ход» —
    это заявление про «сейчас», которого никто не проверял. Проверка сравнивает
    метку бара с московскими часами.

    ЧТО ЭТО СЛОМАЛО. `test_volume_events.py` строит бары с фиксированной датой
    (2026-08-03T10:00 и дальше по минутам). Через день такие бары устарели, и
    23 теста разом покраснели — не потому, что обнаружение испортилось, а
    потому, что нарисованное время не догоняет настоящее. Привязать фикстуры к
    «сегодня» нельзя: там есть выходные, короткие дни и утренняя сессия,
    которые обязаны оставаться именно теми днями. Тот же счёт предъявят
    `test_price_events.py` и `test_timeframes.py`, и лучше заплатить по нему
    заранее, чем читать красноту и гадать, регресс это или календарь.

    ПОЧЕМУ ЭТО НЕ ЗАМЕТАНИЕ ПОД КОВЁР. Свежесть не остаётся непроверенной: у
    неё есть собственные файлы `test_scanner_freshness.py` и
    `test_price_freshness.py`, где часы передаются явным параметром `at`, и где
    двухчасовой бар обязан молчать, а свежий — говорить. Здесь же отключаются
    ровно пороги времени и ровно в перечисленных файлах; остальные пороги — пол
    в рублях, тонкая база, кратность, размер ноги — работают.

    Адресность важнее краткости: фикстура смотрит на имя файла, чтобы правило
    случайно не расползлось на соседей.
    """
    if request.node.fspath.basename not in _TIMELESS:
        return
    _lift(monkeypatch, "src.analysis.volume_events")
    _lift(monkeypatch, "src.analysis.price_events")
