"""
Поле не должно называться дневным, если считается по трём часам.

Ошибка, ради которой написан файл: в контексте лежало
    "day_structure": _struct
где _struct считался по 36 пятиминуткам, то есть по ТРЁМ ЧАСАМ. Замер на
27 546 срезах (12 бумаг × 181 день, каждый час сессии): трёхчасовая структура
совпадает с настоящей структурой сессии в 54.4% случаев, к вечеру — в 42%,
и в 3.5% показывает ПРОТИВОПОЛОЖНОЕ направление.

Поле идёт в classify_market_state как intraday_structure, то есть участвует в
решении TREND_UP / TREND_DOWN.

Важно, почему чинится подпись, а не окно. Проверял и структуру всей сессии:
доходность следующего часа, разница «вверх минус вниз» — окно 3ч даёт +0.0004%
(t=0.04), вся сессия +0.0153% (t=1.27). Оба результата неотличимы от шума и
втрое меньше издержек 0.05%. Менять окно не на что; надо перестать выдавать
трёхчасовое число за дневное.
"""
from pathlib import Path

SRC = Path(__file__).resolve().parents[1] / "src/agent/intraday_analyst.py"


def test_field_named_by_what_it_measures():
    """Есть поле structure_3h — имя говорит про окно."""
    src = SRC.read_text()
    assert '"structure_3h"' in src


def test_session_coverage_is_exposed():
    """
    Наружу отдаётся доля сессии, покрытая окном. Без неё потребитель не может
    отличить утро (окно ≈ вся сессия, 100% совпадения) от вечера (42%).
    """
    src = SRC.read_text()
    assert '"structure_session_cover"' in src
    assert "_struct_cover" in src


def test_window_size_is_reported():
    """Сколько баров реально взято — тоже наружу."""
    src = SRC.read_text()
    assert '"structure_3h_bars"' in src


def test_measurement_is_written_down_next_to_the_code():
    """
    Числа замера должны стоять рядом с кодом. Без них следующий агент увидит
    «странное окно 36» и либо расширит его (не поможет — проверено), либо
    оставит подпись «дня» (вернёт ошибку).
    """
    src = SRC.read_text()
    assert "54.4%" in src, "нет доли совпадения с настоящей структурой сессии"
    assert "t=1.27" in src or "0.0153" in src, "нет результата проверки широкого окна"


def test_coverage_math():
    """Доля покрытия считается как окно / прошедшие бары, не больше единицы."""
    for bars, total, expect in [(36, 36, 1.0), (36, 72, 0.5), (36, 180, 0.2),
                                (36, 20, 1.0)]:
        cover = round(min(1.0, bars / total), 2)
        assert cover == expect


def test_legacy_alias_kept():
    """
    day_structure оставлен как псевдоним: удалять поле, которое читают
    потребители, в одном коммите с переименованием — это два изменения сразу.
    """
    src = SRC.read_text()
    assert '"day_structure"' in src
